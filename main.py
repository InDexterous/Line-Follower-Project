from machine import Pin, PWM, ADC
import time

# ============================================================
# ΚΙΝΗΤΗΡΕΣ - ποια Pins του pico συνδεονται με το μοτερ LN298N
# ============================================================
IN1 = Pin(15, Pin.OUT); IN2 = Pin(14, Pin.OUT) #κατευθυνση αριστερου μοτερ (μπροστα/πισω)
IN3 = Pin(16, Pin.OUT); IN4 = Pin(17, Pin.OUT) #κατευθυνση δεξιου μοτερ

enable1 = PWM(Pin(2)); enable2 = PWM(Pin(7)) #ταχυτητα μεσω PWM. Αντί να δίνουν σταθερό ρεύμα, ανοιγοκλείνουν το ρεύμα προς τα μοτέρ πάρα πολλές φορές το δευτερόλεπτο.
enable1.freq(1000); enable2.freq(1000) #με 1000 παλμους/second. Το freq είναι σαν να ρωταμε "πόσες φορές ανά δευτερόλεπτο ανοιγωκλεινω ρευμα;". δεν αλλάζει το αποτέλεσμα, μόνο την ακρίβεια

# ============================================================
# ΑΙΣΘΗΤΗΡΕΣ — ΑΝΑΛΟΓΙΚΟΙ (ADC) - κανονικα, εχουμε 5. χρησιμοποιουμε τους 3 ομως (CENTER, LEFT CENTER, RIGHT CENTER)
# ============================================================
left_ir   = ADC(Pin(26))
center_ir = ADC(Pin(27))
right_ir  = ADC(Pin(28))
#Τα GP26/27/28 είναι τα μόνα pins του Pico με ADC. Δεν μπορουμε να συνδεσουμε αισθητηρες σε αλλα PINS εκτος απο αυτα τα 3.

SENSORS = [left_ir, center_ir, right_ir] #στην λιστα sensors απλα αποθηκευουμε και τους 3 αισθητηρες


# ============================================================
# ΡΥΘΜΙΣΕΙΣ PID. Εδω γινονται οι main αλλαγες
# ============================================================
BASE_SPEED = 40000 #ταχυτητα και των 2 μοτερ στην ευθεια
RECOVERY_SPEED  = 14000  # ταχυτητα αναζητησης οταν η γραμμη χαθει. Κανονικα καλο ειναι -> RECOVERY_SPEED = BASE_SPEED × 0.6 (μεση τιμη, προσαρμοζουμε ομως αναλογα τις αναγκεσ)

KP = 5400 # Δυναμη στροφης. Ποσο δυνατα στριβει οταν βλεπει αποκλιση.
#Oscillation (ζιγκ ζαγκ) -> ΚΑΤΕΒΑΖΟΥΜΕ
#Χανει τις στροφες ή βγαινει εκτος -> ΑΝΕΒΑΖΟΥΜΕ
#Αργη αντιδραση -> ΑΝΕΒΑΖΟΥΜΕ

KI = 0 #αφηνουμε 0 συνηθως. Κανονικα συσσωρευει τα errors αλλα δε χρειαζεται εδω

KD = 2500 #Φρένο / σταθερότητα. Το KD πρεπει παντα να ειναι μικροτερο απο KP. καλο ειναι -> KD = KP x 0.3
#αποτομες διορθωσεισ -> ΚΑΤΕΒΑΖΟΥΜΕ
#Oscilization (παρολο το σωστο KP) -> ΑΝΕΒΑΖΟΥΜΕ 
#Νευρικες μικρο-διορθωσεις -> ΚΑΤΕΒΑΖΟΥΜΕ

MAX_CORRECTION = int(BASE_SPEED * 0.65)  # 12750 — αντικαθιστά το clamp
DEADBAND = 0.08 #Αγνοεί σφάλματα μικρότερα από αυτή την τιμή. Σταματάει μικρο-διορθώσεις στην ευθεία.
#τρεμει/κουναει στην ευθεια -> ΑΝΕΒΑΖΟΥΜΕ (λιγο, κατα 0.2)
#πηγαινει λιγο πλαγια χωρις διορθωση -> ΚΑΤΕΒΑΖΟΥΜΕ (λιγο, κατα 0.2)

SMOOTH   = 0.75 #ποσο αργα αλλαζουν ταχυτητα τα μοτερ. 0.0 -> αμεσα 0.9 -> πολυ αργα
#αποτομες αλλαγες ταχυτητας -> ΑΝΕΒΑΖΟΥΜΕ (κατα 0.05 π.χ)
#αργη αντιδραση σε στροφες -> ΚΑΤΕΒΑΖΟΥΜΕ (κατα 0.05 π.χ)
#Oscilliation με καθυστερηση -> ΚΑΤΕΒΑΖΟΥΜΕ

MAX_INTEGRAL = 1.0   # όριο για anti-windup. (δεν το πειραζουμε)

MIN_SPEED = -(BASE_SPEED * 0.45)  # μέγιστη αντίστροφη ταχύτητα στις στροφές

LEFT_TRIM  = 1.00 #αφηνουμε 1 
RIGHT_TRIM = 0.97 #επειδη ο αριστερος τροχος τρεχει λιγο πιο δυσκολα, βαζουμε το δεξι μοτερ να τρεχει στο 97% για να ισορροπισει την ασυμετρια

LOST_TIMEOUT_MS = 300 #ποσο γρηγορα σταματαει αν χασει την γραμμη. (300 -> αμεσως σχεδον. 600 -> κανει περιστροφη και συνεχιζει αναποδα π.χ)

# ============================================================
# CALIBRATION
# ============================================================
_black_min = [65535, 65535, 65535]
_white_max = [0,     0,     0    ]

def calibrate(duration_s=8): #το κανουμε calibraiton για 8 δευτερολεπτα
    print("=" * 40)
    print("  ΒΑΘΜΟΝΟΜΗΣΗ")
    print(f"  Κούνα τον ρομπότ πάνω από τη γραμμή")
    print(f"  και το λευκό για {duration_s} δευτερόλεπτα...")
    print("=" * 40)

    start = time.ticks_ms()
    while time.ticks_diff(time.ticks_ms(), start) < duration_s * 1000:
        for i, s in enumerate(SENSORS):
            val = s.read_u16() #διαβαζει οσο εμεις κανουμε calibration
            if val < _black_min[i]: _black_min[i] = val  #κραταει Min/max για καθε αισθητηρα
            if val > _white_max[i]: _white_max[i] = val

        elapsed  = time.ticks_diff(time.ticks_ms(), start)
        remaining = duration_s - elapsed // 1000
        raw = [s.read_u16() for s in SENSORS]
        print(f"  [{remaining:2d}s]  L={raw[0]:5d}  C={raw[1]:5d}  R={raw[2]:5d}")
        time.sleep_ms(100)

    print()
    names  = ['Αριστερά', 'Κέντρο', 'Δεξιά']
    all_ok = True
    for i in range(3):
        contrast = _white_max[i] - _black_min[i]
        ok       = contrast > 5000 #ελεγχει αν η διαφορα τους > 5000
        if not ok: all_ok = False
        status = "OK" if ok else "ΧΑΜΗΛΗ ΑΝΤΙΘΕΣΗ — έλεγξε ύψος αισθητήρα!"
        print(f"  {names[i]}: μαύρο={_black_min[i]:5d}  "
              f"λευκό={_white_max[i]:5d}  [{status}]")
    print()
    if all_ok:
        print("  Βαθμονόμηση επιτυχής!")
    else:
        print("  ΠΡΟΕΙΔΟΠΟΙΗΣΗ: Ρύθμισε ύψος αισθητήρων σε 5-10mm.")
    print("=" * 40)

# ============================================================
# ΑΝΑΛΟΓΙΚΟ ΣΦΑΛΜΑ — weighted average
# ============================================================
POSITIONS = [-1.0, 0.0, 1.0]   # Αριστερά, Κέντρο, Δεξιά

def read_error(): #μετατρεπει τις αναλογικες τιμες σε εναν αριθμο που δειχνει που βρισκεται η γραμμη
    #-1.0 -> γραμμη τελειως αριστερα
    #0.0 -> γραμμη στο κεντρο
    #1.0 -> γραμμη τελειως δεξια
    num   = 0.0
    denom = 0.0
    for i in range(3):
        raw  = SENSORS[i].read_u16()
        span = _white_max[i] - _black_min[i]
        if span == 0:
            norm = 0.0
        else:
            norm = 1.0 - (raw - _black_min[i]) / span
            norm = max(0.0, min(1.0, norm))

        num   += POSITIONS[i] * norm
        denom += norm

    if denom < 0.1:
        return None             # Κανένας αισθητήρας δεν βλέπει γραμμή
    return num / denom          # -1.0 έως +1.0

# ============================================================
# ΚΙΝΗΤΗΡΕΣ
# ============================================================

def motors(left_speed, right_speed): #ελεγχει καθε μοτερ ξεχωριστα. δεχεται αρνητικες τιμες για αντιστροφη φορα (πιο ομαλο Pivot σε εντονες στροφες)
    # Αριστερό μοτέρ
    if left_speed >= 0:
        IN1.value(1); IN2.value(0)
    else:
        IN1.value(0); IN2.value(1)
    enable1.duty_u16(max(0, min(65535, int(abs(left_speed)))))

    # Δεξί μοτέρ
    if right_speed >= 0:
        IN3.value(1); IN4.value(0)
    else:
        IN3.value(0); IN4.value(1)
    enable2.duty_u16(max(0, min(65535, int(abs(right_speed)))))

def stop():
    enable1.duty_u16(0); enable2.duty_u16(0)
    IN1.low(); IN2.low(); IN3.low(); IN4.low()

# ============================================================
# ΕΚΚΙΝΗΣΗ
# ============================================================
print("Εκκίνηση βαθμονόμησης...")
calibrate(duration_s=5)

print("\nΕκκίνηση σε 3 δευτερόλεπτα...")
time.sleep(3)
print("GO!")

# ============================================================
# PID ΜΕΤΑΒΛΗΤΕΣ
# ============================================================
last_error    = 0.0
integral      = 0.0
last_turn     = "none"
lost_since_ms = None

_smooth_left  = float(BASE_SPEED)   # Αρχικοποίηση smoothing
_smooth_right = float(BASE_SPEED)

# ============================================================
# ΚΥΡΙΟΣ ΒΡΟΧΟΣ
# ============================================================
while True:

    error = read_error()

    # --- Χαμένη γραμμή ---
    if error is None:
        if lost_since_ms is None:
            lost_since_ms = time.ticks_ms()
            print("Γραμμή χάθηκε — ανάκτηση...")

        elapsed_lost = time.ticks_diff(time.ticks_ms(), lost_since_ms)
        # Αν δεν την βρει -> σταματαει
        if elapsed_lost >= LOST_TIMEOUT_MS: #300 ms (το ειχαμε βαλει πιο πανω στισ ΡΥΘΜΙΣΕΙΣ PID
            stop() #Αν δεν την βρει -> σταματαει
            print("=" * 40)
            print("  ΤΕΡΜΑΤΙΣΜΟΣ")
            print("=" * 40)
            break
        #οταν κανενας αισθητηρας δεν βλεπει γραμμη -> στριβει προς την τελευταια γνωστη κατευθυνση για 300 ms.
        if last_turn == "left":
            motors(-RECOVERY_SPEED, RECOVERY_SPEED) #Ψαχνει με την ταχυτητα που ορισαμε στις ΡΥΘΜΙΣΕΙΣ PID
        elif last_turn == "right":
            motors(RECOVERY_SPEED, -RECOVERY_SPEED)
        else:
           stop()

        time.sleep_ms(8)
        continue

    # Γραμμή βρέθηκε — μηδένισε χρονόμετρο
    lost_since_ms = None
    
    # --- Κατεύθυνση για recovery ---
    #θυμαται προς τα που εστριβε πριν χαθει η γραμμη. ετσι το recovery speed ψαχνει την σωστη καττευθυνση.
    if error < -DEADBAND:
        last_turn = "left"
    elif error > DEADBAND:
        last_turn = "right"
        
    # --- Deadband ---
    #αν η γραμμη ειναι σχεδον κεντρο (+- 8%) το ρομποτ παει ΕΥΘΕΙΑ ΧΩΡΙΣ ΔΙΟΡΘΩΣΗ. (εμποδιζει το τρεμουλο στην ευθεια)
    if abs(error) < DEADBAND: #0.08 το ειχαμε βαλει
        error = 0.0

    # --- PID ---
    # --- Adaptive Speed ---
    
    #1. Πιο επιθετική μείωση ταχύτητας στις στροφές -> μειωση
    effective_speed = int(BASE_SPEED * (1.0 - 0.25 * abs(error))) #μειωνει αυτοματα ταχυτητα στις στροφες.
    #Οσο πιο μεγαλο το σφαλμα (οσο πιο κλειστη η στροφη) τοσο μειωνει τη βασικη του ταχυτητα
    derivative = error - last_error #ποσο γρηγορα αλλαζει το σφαλμα
    integral  += error #το αθροισμα των σφαλματων (δεν χρησιμοποιειται)
    integral   = max(-MAX_INTEGRAL, min(MAX_INTEGRAL, integral))  # anti-windup
    
    correction = int(KP * error + KI * integral + KD * derivative) #δυναμη της διορθωσης
    #KP * error -> οσο πιο μακρια η γραμμη, τοσο πιο δυνατη η στροφη
    #KD * derivative -> φρεναρει οταν το error μειωνεται γρηγορα (αποτρεπει υπερ-διορθωση)
    #KI * integral -> βγαινει παντα 0 αφου βαλαμε οτι KI = 0.
    
    correction = max(-MAX_CORRECTION, min(MAX_CORRECTION, correction)) #clamp
    #αν ο τυπος του PID βγαλει ενα μεγαλο νουμερο, το περιοριζουμε στα ορια του MAX_CORRECTION (που βαλαμε στις ρυθμισεισ PID) για να μην τρελαθουν τα μοτερ.

    last_error = error
    
    #--- ΥΠΟΛΟΓΙΣΜΟΣ ΤΡΟΧΩΝ ---
    #Παιρνει την ταχυτητα που πρεπει το ρομποτ να παει ευθεια (effective speed) και την πολ/ζει με το TRIM για διορθωση και προσθετει την διορθωση απτην μια ροδα αλλα την αφαιρει απο την αλλη
    target_left  = int(effective_speed * LEFT_TRIM)  + correction
    target_right = int(effective_speed * RIGHT_TRIM) - correction
    #Το trim εφαρμοζεται μονο στο base και οχι στην διορθωση
    
    
    #αντι να δωσουμε την παραπανω ταχυτητα στα μοτερ, πανε με αυτην την ταχυτητα σιγα σιγα κρατωντας ποσοστο της προηγουμενης καταστασης και ποσοστο της καινουργιας εντολης και τα προσθετει.
    _smooth_left  = SMOOTH * _smooth_left  + (1 - SMOOTH) * target_left 
    _smooth_right = SMOOTH * _smooth_right + (1 - SMOOTH) * target_right
    
    motors(max(MIN_SPEED, _smooth_left), max(MIN_SPEED, _smooth_right)) #στελνουμε την νεα ταχυτητα στα μοτερ καλωντας την συναρητηση motors()
    #η max(a, b) παιρνει 2 τιμες και επιστρεφει την μεγαλυτερη οπου εδω ειναι: a -> MIN_SPEED και b -> _smooth_left ή right).
    #καλο για κλειστες στροφες γτ αν φρεναρει πολυ η ροδα, η τιμη θα βγει αρνητικη και το ρομποτ θα χασει την γραμμη σπινιαροντας γυρω γυρω. αρα το max ειναι σαν να βαζει κοφτη
    #π.χ Με το max(-5000, -15000): Το -5000 είναι μεγαλύτερο από το -15000. Άρα η συνάρτηση "κόβει" το -15000 και στέλνει στα μοτέρ το -5000.
    
    time.sleep_ms(8)


